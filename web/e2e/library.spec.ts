import {test,expect} from './fixtures';
import {tmpdir} from 'node:os';
import {join} from 'node:path';

test('bulk publishing includes edits; deleting questions preserves personal history',async({page,request},testInfo)=>{
 const errors:string[]=[];
 const title='Library test '+crypto.randomUUID();
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');await page.getByRole('button',{name:'Course library',exact:true}).click();
 await page.getByLabel('Lesson title').fill(title);
 await page.getByLabel('Document',{exact:true}).setInputFiles({name:'lesson.txt',mimeType:'text/plain',buffer:Buffer.from('Eu sunt acasă în fiecare zi.\nNoi avem o casă foarte frumoasă.\nTu mergi la școală dimineața.')});
 const uploaded=page.waitForResponse(r=>r.url().endsWith('/api/materials')&&r.request().method()==='POST');
 await page.getByRole('button',{name:'Upload document'}).click();const materialID=(await(await uploaded).json()).id;
 await expect(page.getByLabel('I checked this text')).toHaveCount(0);
 await expect(page.getByRole('button',{name:'Generate drafts',exact:true})).toBeEnabled();
 await page.getByRole('combobox',{name:'Generation method',exact:true}).selectOption('local');
 let releaseGeneration!:()=>void;
 const generationReady=new Promise<void>(resolve=>{releaseGeneration=resolve});
 await page.route('**/api/materials/*/generate',async route=>{await generationReady;await route.fulfill({status:503,json:{error:'Generation check unavailable. Please retry.'}})},{times:1});
 await page.getByRole('button',{name:'Generate drafts',exact:true}).click();
 try{
  await expect(page.getByRole('status').filter({hasText:'Generating questions…'})).toBeVisible();
  await expect(page.getByRole('button',{name:'Generating…',exact:true})).toBeDisabled();
  await page.locator('.generation-progress').screenshot({path:join(tmpdir(),`romana-loader-${testInfo.project.name}.png`)});
 }finally{releaseGeneration()}
 await expect(page.getByRole('alert')).toContainText('Generation check unavailable. Please retry.');
 await expect(page.locator('.generation-progress')).toHaveCount(0);
 await expect(page.getByRole('button',{name:'Generate drafts',exact:true})).toBeEnabled();
 await page.getByRole('button',{name:'Generate drafts',exact:true}).click();
 await expect(page.locator('article.draft')).toHaveCount(3);
 const third=page.locator('article.draft').nth(2);
 await third.getByRole('button',{name:'Delete question',exact:true}).click();
 await third.getByRole('button',{name:'Cancel',exact:true}).click();
 await expect(page.locator('article.draft')).toHaveCount(3);
 await third.getByRole('button',{name:'Delete question',exact:true}).click();
 await third.getByRole('button',{name:'Confirm deletion',exact:true}).click();
 await expect(page.locator('article.draft')).toHaveCount(2);
 const explanation='Recall sunt: Eu sunt acasă în fiecare zi.';
 await page.locator('article.draft').first().getByRole('button',{name:'Edit question',exact:true}).click();
 await page.locator('article.draft').first().getByRole('combobox',{name:'Exercise type',exact:true}).selectOption('cloze');
 await page.locator('article.draft').first().getByRole('textbox',{name:'Explanation',exact:true}).fill(explanation);
 await page.getByLabel('Select all draft questions',{exact:true}).check();
 await expect(page.getByRole('button',{name:'Publish selected (2)',exact:true})).toBeEnabled();
 await expect(page.getByLabel('I reviewed the selected questions')).toHaveCount(0);
 await page.getByRole('button',{name:'Publish selected (2)',exact:true}).click();
 await expect(page.locator('article.published')).toHaveCount(2);
 const detail=await(await request.get('/api/materials/'+materialID)).json();
 expect(detail.exercises[0].explanation).toBe(explanation);
 expect(detail.exercises[0].kind).toBe('cloze');expect(detail.exercises[0].options).toEqual([]);
 const exercises=await(await request.get('/api/exercises?materialId='+materialID)).json();
 expect(exercises).toHaveLength(2);expect(exercises[0]).not.toHaveProperty('answers');expect(exercises[0]).not.toHaveProperty('sourceQuote');
 await page.screenshot({path:join(tmpdir(),`romana-library-${testInfo.project.name}.png`),fullPage:true});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 const selected=page.waitForResponse(r=>new URL(r.url()).pathname==='/api/practice/question');
 await page.getByRole('button',{name:'Practice this lesson'}).click();const chosen=await(await selected).json();
 const chosenDraft=detail.exercises.find((q:{id:string})=>q.id===chosen.id);
 const typed=page.getByLabel('Your answer',{exact:true});
 await expect(page.locator('.exercise-prompt')).toHaveText(chosen.prompt);
 if(await typed.count())await typed.fill(chosenDraft.answers[0]);else await page.locator('.options').getByRole('button',{name:chosenDraft.answers[0],exact:true}).click();
 await page.getByRole('button',{name:'Check answer',exact:true}).click();
 await expect(page.getByText('Nicely done.',{exact:true})).toBeVisible();await expect(page.getByText('Saved to your history',{exact:true})).toBeVisible();
 await expect(page.locator('.feedback blockquote')).toHaveCount(0);
 await page.reload();await expect(page.locator('.stats')).toHaveCount(0);
 await page.getByRole('button',{name:'Course library',exact:true}).click();await page.getByRole('button',{name:new RegExp(title)}).click();
 const published=page.locator('article.published').first();
 await published.getByRole('button',{name:'Delete question',exact:true}).click();await published.getByRole('button',{name:'Confirm deletion',exact:true}).click();
 await expect(page.locator('article.published')).toHaveCount(1);
 expect(await(await request.get('/api/exercises?materialId='+materialID)).json()).toHaveLength(1);
 await page.getByRole('button',{name:'History',exact:true}).click();
 await expect(page.locator('.history-item')).toHaveCount(1);await expect(page.locator('.history-item')).toContainText(chosenDraft.explanation);
 const mixed=page.waitForResponse(r=>new URL(r.url()).pathname==='/api/practice/question'&&!new URL(r.url()).search);
 await page.getByRole('button',{name:'Practice',exact:true}).click();const question=await(await mixed).json();
 expect(question.id).toBeTruthy();
 await expect(page.locator('.exercise-prompt')).toHaveCount(1);
 await expect(page.locator('.question-preview')).toHaveCount(0);
 await expect(page.getByRole('button',{name:'Start a little practice'})).toHaveCount(0);
 await expect(page.locator('.exercise-prompt')).toHaveText(question.prompt);
 expect(errors).toEqual([]);
});
